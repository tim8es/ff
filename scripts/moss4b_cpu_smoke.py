"""FF public-reference MOSS-TTS 4B CPU feasibility test (never use user audio)."""
import os
import resource
import subprocess
from pathlib import Path

def main():
    import torch
    import torchaudio
    from transformers import AutoModel, AutoProcessor

    torch.set_num_threads(2)
    ident="OpenMOSS-Team/MOSS-TTS-Local-Transformer-v1.5"
    print("CPU RAM before:", resource.getrusage(resource.RUSAGE_SELF).ru_maxrss, "KB",flush=True)
    processor=AutoProcessor.from_pretrained(ident,trust_remote_code=True)
    processor.audio_tokenizer=processor.audio_tokenizer.to("cpu")
    print("Processor loaded, peak RSS", resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,flush=True)
    model=AutoModel.from_pretrained(
        ident,trust_remote_code=True,attn_implementation="eager",
        torch_dtype=torch.bfloat16,low_cpu_mem_usage=True,
    ).to("cpu")
    model.eval()
    print("4B model loaded, peak RSS",resource.getrusage(resource.RUSAGE_SELF).ru_maxrss,flush=True)
    samples={
        "ru":"Этот короткий тест проверяет качество русской речи на модели MOSS.",
        "en":"This short test checks the quality of English speech generated by MOSS.",
    }
    Path("out").mkdir(exist_ok=True)
    with torch.no_grad():
        for lang,text in samples.items():
            conv=[[processor.build_user_message(text=text,language={"ru":"Russian","en":"English"}[lang])]]
            batch=processor(conv,mode="generation")
            output=model.generate(input_ids=batch["input_ids"].to("cpu"),
                                  attention_mask=batch["attention_mask"].to("cpu"),
                                  max_new_tokens=384,do_sample=True,
                                  audio_temperature=1.7,audio_top_p=0.8,audio_top_k=25)
            decoded=processor.decode(output)
            candidate=next((m for m in decoded if m and m.audio_codes_list),None)
            if candidate is None:raise RuntimeError("Decoder did not return audio")
            audio=candidate.audio_codes_list[0].float().cpu()
            path=Path("out")/f"moss4b_{lang}.wav"
            torchaudio.save(str(path),audio,processor.model_config.sampling_rate)
            subprocess.run(["ffmpeg","-v","error","-xerror","-i",str(path),"-f","null","-"],check=True)
            print("PASS",lang,str(path),flush=True)

if __name__=="__main__":main()
